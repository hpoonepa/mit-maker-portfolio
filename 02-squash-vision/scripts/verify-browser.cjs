const { chromium, expect } = require('../src/squashvision/web/node_modules/@playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
  const out = path.resolve(__dirname, '../runtime/browser-review');
  fs.mkdirSync(out, { recursive: true });
  const base = 'http://127.0.0.1:8950';
  const matchId = '5ebf3351-5a26-48c0-839b-5da930aa7913';
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  const errors = [];
  const checks = [];
  page.on('pageerror', error => errors.push(error.message));
  const checkWidth = async (label) => {
    const size = await page.evaluate(() => ({ viewport: innerWidth, page: document.documentElement.scrollWidth }));
    assert(size.page <= size.viewport, `${label} overflow: ${JSON.stringify(size)}`);
    checks.push(`${label}: no horizontal overflow`);
  };
  await page.goto(base);
  await expect(page.getByRole('heading', { name: 'Matches', exact: true })).toBeVisible();
  await page.locator('.match-preview[data-ready="true"]').waitFor();
  await page.screenshot({ path: `${out}/library-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await checkWidth('Mobile library');
  await page.screenshot({ path: `${out}/library-mobile.png`, fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('link', { name: 'Open', exact: true }).click();
  await expect(page.locator('.rail-progress')).toContainText('Analysis ready');
  await expect(page.locator('.overlay-context')).toHaveCount(0);
  await expect(page.locator('.timeline-event').filter({ hasText: 'Evidence window' })).toHaveCount(0);
  const video = page.locator('video[aria-label="Match video evidence"]');
  await expect.poll(() => video.evaluate(v => v.readyState)).toBeGreaterThanOrEqual(2);
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await expect.poll(() => video.evaluate(v => v.currentTime)).toBeGreaterThan(2);
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  checks.push('Real video decodes, plays and pauses');
  await page.getByRole('slider', { name: 'Match playback position' }).fill('12.5');
  await expect.poll(() => video.evaluate(v => v.currentTime)).toBeGreaterThan(12.4);
  await page.getByRole('button', { name: 'Next evidence frame' }).click();
  await expect.poll(() => video.evaluate(v => v.currentTime)).toBeGreaterThan(12.5);
  await page.locator('.overlay-settings summary').click();
  await expect(page.getByRole('checkbox', { name: 'Skeleton', exact: true })).toBeChecked();
  await expect(page.getByRole('checkbox', { name: 'Boxes', exact: true })).not.toBeChecked();
  await expect(page.getByRole('checkbox', { name: 'Short trail', exact: true })).not.toBeChecked();
  await expect(page.getByRole('checkbox', { name: 'Uncertainty', exact: true })).not.toBeChecked();
  await page.getByRole('checkbox', { name: 'Boxes', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Boxes', exact: true }).uncheck();
  await page.waitForTimeout(300);
  const canvas = await page.locator('.video-overlay canvas').evaluate(c => {
    const pixels = c.getContext('2d').getImageData(0, 0, c.width, c.height).data;
    let visible = 0;
    for (let i = 3; i < pixels.length; i += 4) if (pixels[i]) visible++;
    return { width: c.width, height: c.height, visible };
  });
  assert(canvas.visible > 100, 'Overlay canvas is blank');
  checks.push('Seek, evidence frame stepping, pose toggle and rendered tracking overlays');
  await page.locator('.overlay-settings summary').click();
  await page.screenshot({ path: `${out}/analysis-desktop.png`, fullPage: true });
  await page.locator('.video-stage').screenshot({ path: `${out}/tracking-detail.png` });
  await page.getByRole('button', { name: 'Fullscreen evidence', exact: true }).click();
  await expect.poll(() => page.evaluate(() => document.fullscreenElement?.className)).toBe('video-instrument');
  await expect(page.getByRole('button', { name: 'Play', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Exit fullscreen evidence' }).click();
  checks.push('Fullscreen keeps playback controls accessible');
  for (const label of ['Overview', 'Shots', 'Rallies', 'Movement', 'Errors', 'Trajectory', 'Head-to-head', 'Coaching']) {
    await page.getByRole('tab', { name: label, exact: true }).click();
    await expect(page.getByRole('tab', { name: label, exact: true })).toHaveAttribute('aria-selected', 'true');
    await expect(page.getByRole('tabpanel', { name: label, exact: true })).toBeVisible();
  }
  checks.push('All eight report sections render');
  await page.getByRole('tab', { name: 'Overview', exact: true }).click();
  await page.getByRole('button', { name: 'Build local export', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Download completed export' })).toBeVisible({ timeout: 30000 });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download completed export' }).click();
  const download = await downloadPromise;
  await download.saveAs(`${out}/browser-export.zip`);
  assert(fs.statSync(`${out}/browser-export.zip`).size > 1000);
  checks.push('Report export builds and downloads through the UI');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => scrollTo(0, 0));
  await checkWidth('Mobile analysis');
  await page.screenshot({ path: `${out}/analysis-mobile.png`, fullPage: true });
  await page.goto(`${base}/matches/${matchId}/setup`);
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible();
  await expect(page.getByText('Playing area saved', { exact: true })).toBeVisible();
  await expect.poll(() => page.getByLabel('Playing area video').evaluate(v => v.readyState)).toBeGreaterThanOrEqual(2);
  await checkWidth('Mobile setup');
  await page.screenshot({ path: `${out}/setup-mobile.png`, fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: `${out}/setup-desktop.png`, fullPage: true });
  await page.goto(`${base}/matches/${matchId}/processing`);
  await expect(page.getByRole('link', { name: 'View analysis' })).toBeVisible();
  checks.push('Setup and completed processing routes render');
  await page.goto(base);
  await expect(page.getByRole('heading', { name: 'Matches', exact: true })).toBeVisible();
  await page.getByRole('link', { name: /Import video/ }).click();
  await page.getByLabel('Choose one match video').setInputFiles(path.resolve(__dirname, '../runtime/elshorbagy-farag-25s.mp4'));
  const uploadTitle = `Browser upload verification ${Date.now()}`;
  await page.getByLabel('Match title', { exact: true }).fill(uploadTitle);
  await page.getByLabel('Player A', { exact: true }).fill('Test player A');
  await page.getByRole('button', { name: 'Upload match', exact: true }).click();
  const uploadedCard = page.getByRole('listitem').filter({ has: page.getByRole('heading', { name: uploadTitle, exact: true }) });
  await expect(uploadedCard).toBeVisible({ timeout: 30000 });
  await uploadedCard.getByRole('link', { name: 'Open', exact: true }).click();
  await expect(page).toHaveURL(/\/matches\/[^/]+\/setup/);
  await expect(page.getByRole('heading', { name: `${uploadTitle} setup`, exact: true })).toBeVisible();
  checks.push('File selection, metadata and actual multipart video upload reach setup');
  await page.getByRole('button', { name: 'Draw playing area', exact: true }).click();
  const drawArea = page.getByRole('group', { name: 'Draw playing area', exact: true });
  const rectangle = await drawArea.boundingBox();
  assert(rectangle, 'Playing area editor is absent');
  const scale = Math.min(rectangle.width / 1280, rectangle.height / 720);
  const offsetX = (rectangle.width - 1280 * scale) / 2;
  const offsetY = (rectangle.height - 720 * scale) / 2;
  for (const [x, y] of [[374, 384], [902, 384], [1075, 719], [202, 719]]) {
    await drawArea.click({ position: { x: offsetX + x * scale, y: offsetY + y * scale } });
  }
  await page.getByRole('button', { name: 'Save playing area', exact: true }).click();
  await expect(page.getByText('Playing area saved', { exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Start tracking', exact: true })).toBeEnabled();
  await page.reload();
  await expect(page.getByText('Playing area saved', { exact: true })).toBeVisible();
  checks.push('Playing area draws, saves and survives reload; tracking becomes available');
  await page.goto(base);
  const testCard = page.getByRole('listitem').filter({ has: page.getByRole('heading', { name: uploadTitle, exact: true }) });
  await testCard.getByText('More options', { exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await testCard.getByRole('button', { name: 'Delete', exact: true }).click();
  await expect(testCard).toHaveCount(0);
  checks.push('Disposable upload removed through library UI; analyzed demo retained');
  assert.deepEqual(errors, [], `Browser errors: ${errors.join(', ')}`);
  const result = { checkedAt: new Date().toISOString(), base, matchId, checks, canvas, errors };
  fs.writeFileSync(`${out}/verification.json`, `${JSON.stringify(result, null, 2)}\n`);
  console.log(JSON.stringify(result, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
